// A small ESM allowlist works in both Node tests and Pages' older Functions
// compiler, which cannot parse JSON import attributes. Rebuild it from the
// photo manifest on every deployment so admin uploads become readable too.
import fs from 'node:fs'
import { GALLERY_ASSET } from '../lib/gallery-validation.js'
const manifest = JSON.parse(fs.readFileSync(new URL('../src/generated/photos.json', import.meta.url), 'utf8'))
const keys = {}
for (const [collection, photos] of Object.entries(manifest.collections)) {
  for (const photo of photos) {
    if (!photo.original || !photo.panorama) continue
    const key = photo.assets ? photo.assets.full : `${manifest.prefix}/${collection}/originals/${photo.original}`
    if (photo.assets && !GALLERY_ASSET.test(key)) throw new Error('Invalid gallery image key.')
    keys[`${collection}/${photo.original}`] = key
  }
}
fs.writeFileSync(new URL('../src/generated/gallery-media.js', import.meta.url),
  `// Generated by scripts/build-gallery-media.js.\nexport default ${JSON.stringify(keys, null, 2)}\n`)
console.log(`Generated ${Object.keys(keys).length} panorama image routes`)
